"""
Read CKKS parameters from compiled model .conf files.

The .conf file is a JSON file generated by the ACE compiler (fhe_cmplr) during
the poly-to-C lowering phase. It contains context_params with all CKKS
cryptographic parameters needed for key generation.

Field mapping (conf → CKKSParams):
    _poly_degree      → N  (ring polynomial degree)
    _first_mod_size   → q0 (bit size of first modulus)
    _scaling_mod_size → sf (bit size of scaling factor modulus)
    _mul_depth        → mul_depth (multiplicative depth)
    _rot_idxs         → rot_idxs (rotation indices for Galois keys)
    _hamming_weight   → hamming_weight (secret key Hamming weight)
    _sec_level        → sec_level (security level)
    _num_q_parts      → num_q_parts (number of q digit partitions)
    _input_level      → input_level (input ciphertext level)
    _provider         → provider (backend provider ID)
"""

import json
import logging
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any


logger = logging.getLogger(__name__)


@dataclass
class CKKSParams:
    """CKKS cryptographic parameters extracted from a .conf file.

    Attributes:
        N: Ring polynomial degree (e.g., 65536).
        q0: Bit size of the first modulus (e.g., 60).
        sf: Bit size of the scaling factor modulus (e.g., 56).
        mul_depth: Multiplicative depth of the circuit.
        rot_idxs: List of rotation indices for Galois key generation.
        hamming_weight: Secret key Hamming weight (default 192).
        sec_level: Security level (default 0 = 128-bit).
        num_q_parts: Number of q digit partitions for key switching.
        input_level: Input ciphertext level.
        provider: Backend provider ID (0=ant CPU, 3=phantom GPU).
    """

    N: int
    q0: int
    sf: int
    mul_depth: int = 0
    rot_idxs: list[int] = field(default_factory=list)
    hamming_weight: int = 192
    sec_level: int = 0
    num_q_parts: int = 1
    input_level: int = 1
    provider: int = 0

    def to_dict(self) -> dict[str, Any]:
        """Convert to a plain dictionary (for metadata serialization)."""
        return {
            "N": self.N,
            "q0": self.q0,
            "sf": self.sf,
            "mul_depth": self.mul_depth,
            "rot_idxs": self.rot_idxs,
            "hamming_weight": self.hamming_weight,
            "sec_level": self.sec_level,
            "num_q_parts": self.num_q_parts,
            "input_level": self.input_level,
            "provider": self.provider,
        }

    @classmethod
    def from_dict(cls, d: dict[str, Any]) -> "CKKSParams":
        """Create CKKSParams from a dictionary."""
        return cls(
            N=d["N"],
            q0=d["q0"],
            sf=d["sf"],
            mul_depth=d.get("mul_depth", 0),
            rot_idxs=d.get("rot_idxs", []),
            hamming_weight=d.get("hamming_weight", 192),
            sec_level=d.get("sec_level", 0),
            num_q_parts=d.get("num_q_parts", 1),
            input_level=d.get("input_level", 1),
            provider=d.get("provider", 0),
        )

    def __str__(self) -> str:
        rot_count = len(self.rot_idxs)
        return (
            f"CKKSParams(N={self.N}, q0={self.q0}, sf={self.sf}, "
            f"mul_depth={self.mul_depth}, rot_idxs=[{rot_count} items], "
            f"hamming_weight={self.hamming_weight})"
        )


def find_conf_file(compiled_dir: str | Path) -> Path:
    """Find the .conf file in a compiled model directory.

    Args:
        compiled_dir: Path to the compiled model directory.

    Returns:
        Path to the .conf file.

    Raises:
        FileNotFoundError: If no .conf file is found or directory doesn't exist.
    """
    compiled_dir = Path(compiled_dir).resolve()
    if not compiled_dir.is_dir():
        raise FileNotFoundError(f"Compiled directory not found: {compiled_dir}")

    conf_files = list(compiled_dir.glob("*.conf"))
    if not conf_files:
        raise FileNotFoundError(f"No .conf file found in {compiled_dir}")
    if len(conf_files) > 1:
        logger.warning(
            "Multiple .conf files found in %s, using %s",
            compiled_dir,
            conf_files[0],
        )

    return conf_files[0]


def read_conf(conf_path: str | Path) -> tuple[CKKSParams, dict[str, Any]]:
    """Read CKKS parameters from a .conf file.

    The .conf file is a JSON file with a ``context_params`` section containing
    the FHE cryptographic parameters. This function extracts the parameters
    into a :class:`CKKSParams` dataclass for use in key generation.

    Args:
        conf_path: Path to the .conf file.

    Returns:
        A tuple of (CKKSParams, raw_conf_data) where raw_conf_data is the
        full parsed JSON for downstream use.

    Raises:
        FileNotFoundError: If the .conf file doesn't exist.
        ValueError: If required fields are missing from context_params.
    """
    conf_path = Path(conf_path).resolve()
    if not conf_path.exists():
        raise FileNotFoundError(f"Config file not found: {conf_path}")

    with open(conf_path, encoding="utf-8") as f:
        raw_data = json.load(f)

    ctx = raw_data.get("context_params")
    if ctx is None:
        raise ValueError(f"Missing 'context_params' in {conf_path}")

    # Required fields
    required = ["_poly_degree", "_first_mod_size", "_scaling_mod_size"]
    missing = [k for k in required if k not in ctx]
    if missing:
        raise ValueError(f"Missing required fields in context_params: {missing}")

    params = CKKSParams(
        N=ctx["_poly_degree"],
        q0=ctx["_first_mod_size"],
        sf=ctx["_scaling_mod_size"],
        mul_depth=ctx.get("_mul_depth", 0),
        rot_idxs=ctx.get("_rot_idxs", []),
        hamming_weight=ctx.get("_hamming_weight", 192),
        sec_level=ctx.get("_sec_level", 0),
        num_q_parts=ctx.get("_num_q_parts", 1),
        input_level=ctx.get("_input_level", 1),
        provider=ctx.get("_provider", 0),
    )

    logger.info("Loaded CKKS params from %s: %s", conf_path, params)
    return params, raw_data
