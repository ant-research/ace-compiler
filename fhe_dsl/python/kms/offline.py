"""Offline preprocessing for FHE GPU backends (Phantom and ACE).

Provides server-side offline preparation steps:

  - **Offline weight encoding**: convert DE_MSG_F32 weight files to
    DE_PLAINTEXT format, eliminating on-the-fly encoding overhead at
    inference time.

  - **Key saving**: persist generated keys (from a running FHERuntime)
    to disk for offline loading via ``key_path`` / ``key_mode``.

Usage:

    from ace.kms import OfflinePrep

    prep = OfflinePrep(kernel_path=kernel_path)

    # Encode weights
    encoded_pkg = prep.encode_package(package)

    # Save keys (after FHERuntime has generated them)
    key_dir = prep.save_keys("/path/to/keys")
    eval_dir = prep.save_keys("/path/to/eval_keys", eval_only=True)

For backward compatibility, ``OfflineEncoder`` is available as an alias
for ``OfflinePrep``.
"""

import json
import os
import shutil
from pathlib import Path
from typing import Optional


# Backend library name mapping
_BACKEND_LIB_NAMES = {
    "phantom": "libFHErt_phantom.so",
    "ace": "libFHErt_ace.so",
}


def _find_backend_lib(library: str) -> str:
    """Find the FHE runtime shared library for the given backend.

    Args:
        library: Backend name — "phantom" or "ace".

    Returns:
        Absolute path to the library.

    Raises:
        FileNotFoundError: If the library cannot be found.
        ValueError: If the library name is not recognized.
    """
    if library not in _BACKEND_LIB_NAMES:
        raise ValueError(f"Unknown library '{library}'. Must be one of: {', '.join(sorted(_BACKEND_LIB_NAMES))}")

    lib_name = _BACKEND_LIB_NAMES[library]

    # Search order:
    # 1. Relative to this package (editable install)
    # 2. Relative to the ace package (pip install)
    # 3. Common dist-packages paths
    # 4. Environment variable override
    try:
        import torch

        torch_dir = os.path.dirname(torch.__file__)
        candidate = os.path.join(torch_dir, "..", "ace", "lib", lib_name)
        if os.path.exists(candidate):
            return os.path.abspath(candidate)
    except ImportError:
        pass

    package_dir = Path(__file__).resolve().parent
    for candidate in [
        package_dir / ".." / ".." / "ace" / "lib" / lib_name,
        package_dir / "lib" / lib_name,
    ]:
        candidate = candidate.resolve()
        if candidate.exists():
            return str(candidate)

    # Try the installed ace package
    try:
        import ace

        ace_dir = Path(ace.__file__).resolve().parent
        lib_path = ace_dir / "lib" / lib_name
        if lib_path.exists():
            return str(lib_path)
    except ImportError:
        pass

    # Common dist-packages paths
    for prefix in [
        "/usr/local/lib/python3.10/dist-packages",
        "/usr/local/lib/python3.11/dist-packages",
        "/usr/local/lib/python3.12/dist-packages",
    ]:
        candidate = Path(prefix) / "ace" / "lib" / lib_name
        if candidate.exists():
            return str(candidate)

    # Environment variable override
    env_var = f"ACE_{library.upper()}_LIB"
    env_path = os.environ.get(env_var)
    if env_path and os.path.exists(env_path):
        return env_path

    # Fallback: generic env var
    env_path = os.environ.get("ACE_BACKEND_LIB")
    if env_path and os.path.exists(env_path):
        return env_path

    raise FileNotFoundError(f"Cannot find {lib_name}. Set {env_var} environment variable to its path.")


class OfflinePrep:
    """Offline preprocessing for FHE GPU backends.

    Provides two server-side preparation steps:

    1. **Weight encoding**: convert compiled model weights from DE_MSG_F32
       to DE_PLAINTEXT format, eliminating on-the-fly encoding overhead.

    2. **Key saving**: persist keys generated by a running FHERuntime to
       disk, so they can be loaded in subsequent runs via ``key_path`` and
       ``key_mode`` package options.

    Both operations require the backend library (``libFHErt_phantom.so`` or
    ``libFHErt_ace.so``) and, for weight encoding, the compiled FHE kernel
    ``.so`` to provide CKKS parameter symbols.

    Args:
        kernel_path: Path to the compiled FHE kernel ``.so``.  If provided,
            loaded with ``RTLD_GLOBAL`` to resolve backend symbols.
            If ``None``, the caller must ensure symbols are already available
            (e.g. from a prior ``FHERuntime`` invocation).
        library: Backend library — ``"phantom"`` or ``"ace"``.
    """

    def __init__(self, kernel_path: str | None = None, library: str = "phantom"):
        # DISABLED: offline msg→enc encoding no longer builds an encode-only
        # FheContext (EncPolicy::BYPASS removed). prepare_encode_context /
        # finalize_encode_context were deleted; the *_encode_weight_file C
        # exports are orphaned (uncompiled). Pending reimplementation as a
        # standalone encoding tool that does not construct a full FheContext.
        raise NotImplementedError(
            "OfflinePrep is disabled: the encode-only FheContext path "
            "(EncPolicy::BYPASS) was removed. Pending reimplementation as a "
            "standalone encoding tool. Key saving: use FHERuntime.save_keys; "
            "weight encoding: standalone tool TBD."
        )

    # ------------------------------------------------------------------
    # Weight encoding
    # ------------------------------------------------------------------

    def encode(self, input_weight_file: str, output_weight_file: str | None = None) -> str:
        """Encode weight file from DE_MSG_F32 to DE_PLAINTEXT.

        DISABLED: the encode-only FheContext path was removed (pending a
        standalone encoding tool). Always raises NotImplementedError.
        """
        raise NotImplementedError(
            "OfflinePrep.encode is disabled: the encode-only FheContext path "
            "(EncPolicy::BYPASS) was removed. Pending reimplementation as a "
            "standalone encoding tool."
        )

    @staticmethod
    def update_config(config_path: str, encoded_weight_file: str) -> str:
        """Update the .conf file to point to the encoded weight file.

        Sets ``rt_data_info._entry_type`` to 2 (DE_PLAINTEXT) and updates
        ``_file_name`` to the encoded weight file path.  Creates a backup
        of the original config file.

        Args:
            config_path: Path to the ``.conf`` JSON file.
            encoded_weight_file: Path to the encoded ``.weight`` file.

        Returns:
            Path to the updated config file.
        """
        config_path = Path(config_path)
        if not config_path.exists():
            raise FileNotFoundError(f"Config file not found: {config_path}")

        # Create backup
        backup_path = config_path.with_suffix(config_path.suffix + ".bak")
        shutil.copy2(str(config_path), str(backup_path))

        # Read, modify, write
        with open(str(config_path)) as f:
            config = json.load(f)

        if "rt_data_info" not in config:
            raise ValueError(f"Config file missing 'rt_data_info' section: {config_path}")

        config["rt_data_info"]["_entry_type"] = 2  # DE_PLAINTEXT
        config["rt_data_info"]["_file_name"] = encoded_weight_file

        with open(str(config_path), "w") as f:
            json.dump(config, f, indent=2)

        return str(config_path)

    def encode_package(self, package: dict) -> dict:
        """Encode weight file from a compiled package and return an updated package.

        DISABLED: depends on :meth:`encode`, which is disabled (pending a
        standalone encoding tool). Always raises NotImplementedError.
        """
        raise NotImplementedError(
            "OfflinePrep.encode_package is disabled: the encode-only FheContext "
            "path (EncPolicy::BYPASS) was removed. TODO: provide a standalone "
            "weight-encoding tool; key saving uses FHERuntime.save_keys."
        )

    # ------------------------------------------------------------------
    # Key saving
    # ------------------------------------------------------------------

    def save_keys(self, key_dir: str, eval_only: bool = False) -> int:
        """Save keys to a directory — DISABLED.

        The retired ctypes ``FHert_*``/``Phantom_*`` path is gone. The supported
        way to save keys is ``ace.fhe.runtime.FHERuntime.save_keys(key_dir,
        eval_only=…)`` (before ``finalize()``), which routes to the backend's
        ``Kms_save_keys`` dlsym contract.

        Always raises :class:`NotImplementedError`.
        """
        raise NotImplementedError(
            "OfflinePrep.save_keys is disabled with the rest of OfflinePrep. "
            "Use ace.fhe.runtime.FHERuntime(...).save_keys(key_dir, eval_only=…)"
            " after init()/inference() instead."
        )


# Backward-compatible alias
OfflineEncoder = OfflinePrep
